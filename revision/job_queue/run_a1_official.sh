#!/usr/bin/env bash
# A1 (flow vs. graph-score ablation) through the official Table 3 reader stages:
# rank Graph-Score (direct_score) and Single-Flow (individual_flow) from the frozen
# graphs, verify at ReFlow's per-query budget with the shared vLLM reader, then the
# meaning-preserving controls and CFR. ReFlow rows are the main-table results.
# Usage: run_a1_official.sh DATASET READER_PORT
set -euo pipefail
[[ "$(hostname)" == "3haoji-A100" ]] || exit 1
DS=$1 PORT=$2
R=/data1/yujia/CausalityRAG_reviewer_baselines_20261023_v1
S=/data1/yujia/CausalityRAG
REPO=/data1/yujia/CausalityRAG_release_no_frontier_repair_20260810
PY=/data1/yujia/envs/graphrag/bin/python
CFG=$R/out/flow_ablation_full8_20261024/configs/$DS.json
OUT=$R/a1_official/$DS
URL=http://127.0.0.1:$PORT/v1 MODEL=qwen2.5-7b
get() { python3 -c "import json,sys;print(json.load(open('$CFG'))[sys.argv[1]])" "$1"; }
RET=$(get input) UNITS=$(get units) GRAPHS=$(get graphs) REFLOW=$(get reflow) POOL=$(get pool) MODE=$(get reader_mode)
export CAUSALITYRAG_READER_MODE=$MODE PYTHONUNBUFFERED=1 TOKENIZERS_PARALLELISM=false
mkdir -p "$OUT/controls"
SHA=$(sha256sum "$POOL" | cut -d' ' -f1)

for m in direct_score individual_flow; do
  [[ -s $OUT/$m.jsonl ]] || (cd "$R" && "$PY" scripts/rank_flow_ablations.py --graphs "$GRAPHS" \
    --shared-pool "$POOL" --expected-pool-sha256 "$SHA" --method "$m" --out "$OUT/$m.jsonl")
done
cp -n "$REFLOW" "$OUT/reflow_1000.jsonl"
cd "$REPO"
[[ -s $OUT/baselines_1000.summary.json ]] || "$PY" "$R/pool_sensitivity/scripts/run_with_reader_timeout.py" 1800 \
  scripts/evaluate_matched_budget_baselines.py \
  --input "$RET" --units-cache "$UNITS" --reflow-results "$OUT/reflow_1000.jsonl" \
  --shared-pool "$POOL" --expected-pool-sha256 "$SHA" \
  --out "$OUT/baselines_1000.jsonl" --summary-out "$OUT/baselines_1000.summary.json" \
  --random-seeds 0 --replacement-seed 0 --n 1000 --k 5 --workers 48 \
  --llm-base-url "$URL" --llm-model "$MODEL" \
  --scores "direct_score=$OUT/direct_score.jsonl" --scores "individual_flow=$OUT/individual_flow.jsonl"
"$PY" scripts/summarize_clean_anchor_flips.py --reflow "$OUT/reflow_1000.jsonl" \
  --baselines "$OUT/baselines_1000.jsonl" --out "$OUT/factual_metrics_1000.json" --reader-mode "$MODE"

# Controls: start from the main paraphrase pool where it still exists; missing
# positions are generated by the same Qwen control editor.
PP=$OUT/controls/paraphrase_pool.jsonl
[[ -s $PP ]] || python3 - "$PP" "$S/out/$DS/controls/paraphrase_pool_top5_v2.jsonl" \
  "$S/out_no_frontier_repair_20260810/$DS/table3_resume/paraphrase_pool.jsonl" \
  "$S/out_table3_final8_20260811/$DS/controls/paraphrase_pool_top5_v2.jsonl" <<'PY'
import json, os, sys
rows = {}
for path in sys.argv[2:]:
    if os.path.exists(path):
        for line in open(path):
            if line.strip():
                r = json.loads(line)
                rows[r["unit_id"]] = r
with open(sys.argv[1], "w") as f:
    for r in rows.values():
        f.write(json.dumps(r) + "\n")
print(f"seed paraphrase rows: {len(rows)}")
PY
for pass in $(seq 1 20); do
  "$PY" scripts/build_paraphrase_control_pool.py --input "$RET" --units-cache "$UNITS" \
    --reflow-results "$OUT/reflow_1000.jsonl" --baseline-results "$OUT/baselines_1000.jsonl" \
    --out "$PP.next" --manifest-out "$PP.manifest.json" --unresolved-out "$PP.unresolved.jsonl" \
    --n 1000 --workers 32 --batch-size 16 --attempts 8 --max-candidates 3 \
    --llm-base-url "$URL" --llm-model "$MODEL" --existing-pool "$PP"
  mv "$PP.next" "$PP"
  unresolved=$(python3 -c "import json;print(json.load(open('$PP.manifest.json')).get('unresolved_positions',-1))")
  echo "paraphrase pass $pass unresolved=$unresolved"
  [[ $unresolved == 0 ]] && break
done
PSHA=$(sha256sum "$PP" | cut -d' ' -f1)
[[ -s $OUT/controls_1000.summary.json ]] || "$PY" "$R/pool_sensitivity/scripts/run_with_reader_timeout.py" 1800 \
  scripts/evaluate_paraphrase_controls.py \
  --input "$RET" --units-cache "$UNITS" --reflow-results "$OUT/reflow_1000.jsonl" \
  --baseline-results "$OUT/baselines_1000.jsonl" --paraphrase-pool "$PP" --expected-pool-sha256 "$PSHA" \
  --out "$OUT/controls_1000.jsonl" --summary-out "$OUT/controls_1000.summary.json" \
  --n 1000 --k 5 --workers 48 --replacement-seed 0 --llm-base-url "$URL" --llm-model "$MODEL"
"$PY" scripts/summarize_paraphrase_controls.py --input "$OUT/controls_1000.jsonl" \
  --out "$OUT/controls_1000.summary.json" --reader-mode "$MODE"
"$PY" /data1/yujia/CausalityRAG_reviewer_baselines_20261023_v1/queue/summarize_adjusted_present_random.py --factual "$OUT/factual_metrics_1000.json" \
  --meaning-preserving "$OUT/controls_1000.summary.json" --out "$OUT/table3_metrics_1000.json"
echo "DONE A1 $DS $(date -Is)"
